// heatFloorNote 说明集体自嘲时烈度至少打到哪一档：0~1 轴写"heat 应 ≥0.6"，
// 鬼叫报告的 0~100 轴写"heat 至少按 61~80 的高烈度档计"。
export function selfMockeryRule(heatFloorNote: string): string {
  return `【自嘲/调侃 = 痛苦信号，不是冷静】
- 散户群常用自嘲、反讽、苦笑表情来表达亏损和恐慌，例如"躺板板""团灭""地板上拳脚相加""根本没有这样的赌场""腰斩了""挂跌停了""物理止跌"，配合😂🤣😅🥶😰🌚等表情。
- 只要调侃的对象是自己/群里的亏损、跌停、套牢、爆仓，就按真实的痛苦和悲观计入：方向照常往悲观拉，烈度不得因为"语气是调侃"而下调，多人轮流自嘲跌停视为集体破防（${heatFloorNote}）。
- 自嘲踏空、追高被埋同理，按对应方向的真实情绪计入。
- 只有调侃内容与行情和盈亏无关（纯段子、闲聊互损）时，才按平静闲聊处理。
- 依然先分清是哪一边在痛：空头被拉升后自嘲，仍按多空持仓视角处理。`;
}

